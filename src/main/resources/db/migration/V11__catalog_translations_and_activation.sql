-- comprensibles pero mal escritos ("Press con barra banco" en vez de "Press de
-- banca con barra"). Esos nombres los lee el participante en la app.
--
-- A partir de aqui el catalogo es reproducible: clonar el repositorio y correr
-- las migraciones da exactamente los mismos nombres, sin llamadas a la IA y sin
-- depender de la base de nadie.
